const known = new Set(KNOWN_PROJECTIONS.map(features => JSON.stringify(features)));

/** Classify a full student projection against the published 63-vector set. */
export function projectionKind(features) {
  if (!Array.isArray(features) || features.length !== 12) {
    throw new TypeError("projectionKind expects one 12-wire projection");
  }
  return known.has(JSON.stringify(features)) ? "old-projection" : "new-projection";
}
